/**
 * The left pill — collapsed by default, expands horizontally on click.
 *
 * Collapsed:   [ 3 + ]    (cart count on left, "+" on right)
 * Expanded:    [ 3 +  |  Shop   Contact   Policies   IG  ]
 */
function LeftNavPill() {
  const [open, setOpen] = useState(false);
  // Mock cart count for now — replace with real cart hook later.
  // Starts at 0 so the cart is visually empty until the user adds items.
  const [cartCount, setCartCount] = useState(0);

  /*
   * Measure the natural width of the nav link list so the pill expands
   * to exactly fit the 4 options — no hardcoded guess, no overshoot.
   * `useLayoutEffect` (not useEffect) ensures we measure before the
   * browser paints, so the first open animation targets the correct
   * width from frame 1 — no "snap" mid-transition.
   */
  const listRef = useRef<HTMLUListElement>(null);
  const [expandedWidth, setExpandedWidth] = useState<number | null>(null);
  useLayoutEffect(() => {
    if (!listRef.current) return;
    const measure = () => {
      if (listRef.current) {
        setExpandedWidth(listRef.current.scrollWidth);
      }
    };
    measure();
    // Re-measure if the window resizes (links could wrap or reflow)
    window.addEventListener("resize", measure);
    return () => window.removeEventListener("resize", measure);
  }, []);

  return (
    <GlassPill
      className="p-[5px]" // tight padding so children touch the rim (scaled down ~17% from p-1.5/6px)
    >
      <div className="relative flex items-center">
        {/*
          Cart count badge. Hidden (width 0, opacity 0) when the cart is
          empty so the pill is just "+" until items are added. Collapses
          smoothly when the count goes 0→1 and back.
        */}
        <div
          className={[
            "flex items-center justify-center",
            "h-6 sm:h-7", // scaled 0.85 from h-7 / h-8
            "rounded-full",
            "bg-white/10",
            "text-[10px] sm:text-[11px] font-semibold tracking-tight text-white", // scaled
            "select-none",
            "overflow-hidden",
            "transition-[width,opacity,margin] duration-300 ease-out",
            cartCount > 0 ? "opacity-100" : "opacity-0",
          ].join(" ")}
          style={{
            width: cartCount > 0 ? 27 : 0, // 0.85 × 32 ≈ 27
            marginRight: cartCount > 0 ? 3 : 0,
          }}
          aria-label={`${cartCount} items in cart`}
          aria-hidden={cartCount === 0}
        >
          {cartCount}
        </div>

        {/*
          "+" toggle button. Rotates 45° when open to read as "×".
          Keeps the same circle footprint so the pill width is stable
          around the toggle.
        */}
        <button
          type="button"
          aria-label={open ? "Close navigation" : "Open navigation"}
          aria-expanded={open}
          onClick={() => setOpen((v) => !v)}
          className={[
            "flex items-center justify-center",
            "h-6 w-6 sm:h-7 sm:w-7", // scaled 0.85 from h-7 w-7 / h-8 w-8
            "rounded-full",
            "bg-white/10 hover:bg-white/15",
            "text-white",
            "transition-transform duration-500 ease-[cubic-bezier(0.22,1,0.36,1)]",
            open ? "rotate-45" : "rotate-0",
          ].join(" ")}
        >
          <svg
            aria-hidden
            viewBox="0 0 12 12"
            className="h-2.5 w-2.5" // scaled from h-3 w-3
            fill="none"
            stroke="currentColor"
            strokeWidth="1.6"
            strokeLinecap="round"
          >
            <path d="M6 1.5v9M1.5 6h9" />
          </svg>
        </button>

        {/*
          Expandable nav list. Sits to the right of the toggle.
          - Width transitions from 0 → natural; opacity + transform
            give it a slide-in feel.
          - overflow-hidden on the inner wrapper clips the slide.
        */}
        <div
          className={[
            "overflow-hidden",
            "transition-[width,opacity,margin] duration-500 ease-[cubic-bezier(0.22,1,0.36,1)]",
            open ? "opacity-100" : "opacity-0",
          ].join(" ")}
          style={{
            // Snap to the measured width of the 4 nav links. We don't
            // guess — the pill is always exactly as wide as it needs to
            // be to show all options, never overshoot, never clip. Falls
            // back to 0 while measurement is pending.
            width: open && expandedWidth !== null ? expandedWidth : 0,
            marginLeft: open && expandedWidth !== null ? 6 : 0,
          }}
          aria-hidden={!open}
        >
          <ul ref={listRef} className="flex items-center gap-0.5 pr-1.5 whitespace-nowrap">
            {NAV_LINKS.map((link) => (
              <li key={link.href}>
                <a
                  href={link.href}
                  className={[
                    "inline-flex items-center justify-center",
                    "h-6 sm:h-7", // scaled 0.85 from h-7 / h-8
                    "px-2.5", // scaled from px-3
                    "rounded-full",
                    "text-[10px] sm:text-[11px] font-medium uppercase tracking-[0.16em]", // slightly tighter tracking to compensate
                    "text-white/85 hover:text-white",
                    "bg-transparent hover:bg-white/10",
                    "transition-colors duration-200",
                    "select-none",
                  ].join(" ")}
                >
                  {link.label}
                </a>
              </li>
            ))}
          </ul>
        </div>
      </div>
    </GlassPill>
  );
}

export function NavPill() {
  const pathname = usePathname();
  // The gender toggle appears everywhere EXCEPT the landing page.
  // On /shop/* it's the catalog switcher; on /product/* it's a quick
  // way to jump to the other gender's catalog without going back to
  // /shop first.
  const showGenderPill =
    pathname !== null &&
    pathname !== "/" &&
    (pathname.startsWith("/shop") || pathname.startsWith("/product"));

  return (
    <header className="pointer-events-none fixed inset-x-0 top-0 z-40 grid grid-cols-[1fr_auto_1fr] items-start gap-3 px-4 pt-5 sm:gap-4 sm:px-6 sm:pt-6">
      {/*
        SVG filter — defined once, referenced by every GlassPill in the
        header via `backdrop-filter: url(#liquid-glass)`. Renders to a
        0×0 element so it doesn't take layout space.
      */}
      <svg
        aria-hidden
        xmlns="http://www.w3.org/2000/svg"
        className="pointer-events-none absolute h-0 w-0"
      >
        <defs>
          <filter
            id="liquid-glass"
            x="0%"
            y="0%"
            width="100%"
            height="100%"
            primitiveUnits="userSpaceOnUse"
            colorInterpolationFilters="sRGB"
          >
            <feImage
              href={DISPLACEMENT_MAP}
              result="displacement_map"
              x="0"
              y="0"
              width="100%"
              height="100%"
              preserveAspectRatio="none"
            />
            <feDisplacementMap
              in="SourceGraphic"
              in2="displacement_map"
              scale={MAX_DISPLACEMENT_PX}
              xChannelSelector="R"
              yChannelSelector="G"
              result="refracted"
            />
            <feImage
              href={SPECULAR_MAP}
              result="specular"
              x="0"
              y="0"
              width="100%"
              height="100%"
              preserveAspectRatio="none"
            />
            <feBlend
              in="specular"
              in2="refracted"
              mode="screen"
              result="composed"
            />
          </filter>
        </defs>
      </svg>

      {/*
        The header is `flex justify-between` so the logo sits centered
        visually (it does — flex centers each child independently with
        justify-between the left pill anchors left, the right one (if
        any) anchors right, and the middle child gets pushed to center).
        Actually `justify-between` only distributes the children; to truly
        center the logo we use a 3-column trick: left pill, centered
        logo, an empty spacer of equal width to the left pill on the
        right. We use a hidden spacer to balance the layout.
      */}
      <div className="pointer-events-auto flex flex-col items-start gap-2">
        <LeftNavPill />
        {showGenderPill ? <GenderPill /> : null}
      </div>
      <div className="pointer-events-auto flex justify-center">
        <LogoPill />
      </div>
      <div aria-hidden />
    </header>
  );
}

export default NavPill;