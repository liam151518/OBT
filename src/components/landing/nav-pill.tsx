/**
 * Top-of-page navigation header with two glass pills:
 *
 *   - Left pill: optional / collapsible nav. Shows a cart count + a "+"
 *     button when collapsed. Clicking the "+" expands the pill
 *     horizontally to reveal Shop / Contact / Policies / IG.
 *
 *   - Center pill: the OBT logo.
 *
 * Both pills share the same Liquid Glass treatment (refraction +
 * specular rim) implemented per kube.io/blog/liquid-glass-css-svg :
 *   1. A precomputed Snell-law displacement map encodes how each pixel
 *      on the glass surface should refract background light. The map is
 *      derived from a Squircle surface profile (Apple's choice) with
 *      refractive index 1.5.
 *   2. A precomputed specular map encodes the rim-light intensity for
 *      a fixed light direction (-60°). The two are combined via
 *      <feBlend mode="screen">.
 *   3. The filter is applied via `backdrop-filter: url(#…)`, which is
 *      Chrome-only (Safari/Firefox don't expose SVG filters through
 *      backdrop-filter per the article). On non-Chromium browsers we
 *      fall back to layered CSS frost + a CSS specular rim.
 *
 * Both maps are generated by `scripts/generate-glass-maps.ts`
 * (run with `npx tsx scripts/generate-glass-maps.ts` after changing
 * glass params).
 *
 * IMPORTANT — filter coordinate system
 * ------------------------------------
 * `primitiveUnits="userSpaceOnUse"` so coordinates inside the filter
 * are in user-space pixels. <feImage width="100%" height="100%"> then
 * stretches the radial displacement field to cover the pill — this is
 * what the article calls "stretching the middle" (circles → rounded
 * rectangles).
 */

const DISPLACEMENT_MAP = "/glass-displacement.png";
const SPECULAR_MAP = "/glass-specular.png";
const MAX_DISPLACEMENT_PX = 22; // matches OUTPUT_MAX_DISPLACEMENT_PX in the generator

/**
 * Tiny UA sniff to detect Chromium-based browsers — the only engines
 * that support `backdrop-filter: url(#svg-filter)` per the article.
 *
 * Safari's UA contains "Chrome" (compatibility string) but not "Edg" /
 * "OPR" / "Brave", so we exclude it.
 */
function useIsChromium(): boolean {
  const [isChromium, setIsChromium] = useState(false);
  useEffect(() => {
    if (typeof navigator === "undefined") return;
    const ua = navigator.userAgent;
    const isBlink =
      /Edg\//.test(ua) ||
      /OPR\//.test(ua) ||
      /Brave/.test(ua) ||
      (/Chrome\//.test(ua) && !/Safari\//.test(ua) && !/Firefox\//.test(ua));
    setIsChromium(isBlink);
  }, []);
  return isChromium;
}

/**
 * The shared Liquid Glass surface — used by every header pill AND the
 * product detail page's panels / chips.
 *
 * Two visual modes:
 *   - `pill` (default): rounded-full, inline-flex, ideal for chips
 *     and small interactive elements
 *   - `panel`: rounded rectangle (use `rounded` prop), block layout,
 *     ideal for larger surfaces like the size guide or info panels
 *
 * Both modes share the same Chrome-only SVG `backdrop-filter: url(#…)`
 * refraction + the layered CSS frost/sheen stack that fires in
 * Safari/Firefox. The SVG filter `#liquid-glass` is defined once in
 * the header SVG; product pages inherit it via the same global def.
 *
 * Pass an `as` to render a different element (e.g. <button>), or use
 * the dedicated `GlassPill` / `GlassSurface` wrappers below.
 */
type GlassShape = "pill" | "panel";

export function Glass({
  children,
  shape = "pill",
  rounded,
  className = "",
  style,
}: {
  children: ReactNode;
  shape?: GlassShape;
  /** Custom border-radius (e.g. "rounded-2xl", "rounded-md"). Overrides the shape default. */
  rounded?: string;
  className?: string;
  style?: CSSProperties;
}) {
  const isChromium = useIsChromium();
  const radiusClass =
    rounded ??
    (shape === "pill" ? "rounded-full" : "rounded-2xl");
  const layoutClass =
    shape === "pill"
      ? "inline-flex items-center"
      : "block";
  return (
    <div
      className={[
        "relative",
        layoutClass,
        radiusClass,
        // Frost fallback (Safari/Firefox). Stacks on top of the
        // SVG backdrop-filter in Chrome.
        "backdrop-blur-xl backdrop-saturate-150",
        // Translucent base — the shader bleeds through
        "bg-white/10",
        // Clip sheen children to the rounded shape
        "overflow-hidden",
        // Drop shadow grounds the glass
        "drop-shadow-[0_8px_22px_rgba(0,0,0,0.5)]",
        className,
      ].join(" ")}
      style={
        isChromium
          ? {
              WebkitBackdropFilter: "url(#liquid-glass)",
              backdropFilter: "url(#liquid-glass)",
              ...style,
            }
          : style
      }
    >
      {/* CSS-layer specular rim — for Safari/Firefox. In Chrome the SVG
          filter provides the rim, but this also adds subtle depth. */}
      <span
        aria-hidden
        className={[
          "pointer-events-none absolute inset-0",
          shape === "pill" ? "rounded-full" : rounded ?? "rounded-2xl",
        ].join(" ")}
        style={{
          boxShadow:
            "inset 0 -1.5px 4px rgba(0,0,0,0.18), inset 0 1px 1px rgba(255,255,255,0.35)",
        }}
      />

      {/* 1px top-edge specular highlight line */}
      <span
        aria-hidden
        className="pointer-events-none absolute inset-x-0 top-0 h-px"
        style={{
          background:
            "linear-gradient(to right, rgba(255,255,255,0) 0%, rgba(255,255,255,0.7) 50%, rgba(255,255,255,0) 100%)",
        }}
      />

      {/* Vertical sheen (top brighter than bottom) — fallback for
          non-Chrome browsers. */}
      <span
        aria-hidden
        className={[
          "pointer-events-none absolute inset-0",
          shape === "pill" ? "rounded-full" : rounded ?? "rounded-2xl",
        ].join(" ")}
        style={{
          background:
            "linear-gradient(to bottom, rgba(255,255,255,0.12) 0%, rgba(255,255,255,0.02) 35%, rgba(255,255,255,0) 60%, rgba(0,0,0,0.04) 100%)",
        }}
      />

      {children}
    </div>
  );
}

/**
 * Pill-shaped glass surface — every chip and round button in the
 * app renders this. Kept as a thin wrapper around <Glass /> for
 * backwards compatibility with existing callers.
 */
export function GlassPill({
  children,
  className = "",
  style,
}: {
  children: ReactNode;
  className?: string;
  style?: CSSProperties;
}) {
  return (
    <Glass shape="pill" className={className} style={style}>
      {children}
    </Glass>
  );
}

/**
 * Panel-shaped glass surface — used for larger rectangles on the
 * product detail page (size guide, info blocks, etc.). Default
 * border-radius is `rounded-2xl`; pass `rounded` to override.
 */
export function GlassSurface({
  children,
  className = "",
  style,
  rounded,
}: {
  children: ReactNode;
  className?: string;
  style?: CSSProperties;
  rounded?: string;
}) {
  return (
    <Glass shape="panel" rounded={rounded} className={className} style={style}>
      {children}
    </Glass>
  );
}

